/**
 * Adopt the UIScene life cycle.
 *
 * iOS 27 will not launch an app built with the iOS 27 SDK that still creates
 * its window in the app delegate. UIKit traps on the main thread before any
 * JavaScript loads:
 *
 *   EXC_BREAKPOINT (SIGTRAP)
 *   UIKitCore  _UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption
 *
 * Apple announced the requirement alongside iOS 26. Expo SDK 57's template
 * predates it: its AppDelegate builds the window in didFinishLaunching and its
 * Info.plist has no scene manifest.
 *
 * This plugin
 *   1. adds a single-scene UIApplicationSceneManifest to Info.plist
 *   2. adds SceneDelegate.swift, which creates the window from the
 *      UIWindowScene and starts React Native in it, and forwards links — with
 *      scenes, URLs and universal links arrive at the scene, not the app delegate
 *   3. edits AppDelegate.swift so it still builds the React Native factory but
 *      leaves the window to the scene
 *
 * The AppDelegate edit matches the generated code exactly and throws if it is
 * not there, so a template change fails at prebuild instead of shipping an app
 * that crashes on launch.
 *
 * A config plugin rather than an Xcode edit because `expo prebuild` regenerates
 * ios/ and would discard anything done by hand.
 */
const fs = require('fs');
const path = require('path');
const {
  withInfoPlist, withAppDelegate, withXcodeProject, withDangerousMod, IOSConfig,
} = require('@expo/config-plugins');

const MODULE_NAME = 'main';   // must match AppDelegate's startReactNative call

const SCENE_DELEGATE = `import UIKit
import React

// UIScene life cycle — required on iOS 27 for apps built with its SDK.
// AppDelegate still builds the React Native factory in didFinishLaunching; the
// window is created here, from the scene, and React Native starts in it.
// Generated by plugins/withSceneLifecycle.js — edit the plugin, not this file.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window   // Expo modules look for the window here
    factory.startReactNative(
      withModuleName: "${MODULE_NAME}",
      in: window,
      launchOptions: appDelegate.launchOptions)

    // A cold start from a link delivers it with the scene connection.
    if let url = connectionOptions.urlContexts.first?.url {
      _ = RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
    }
    if let activity = connectionOptions.userActivities.first {
      _ = RCTLinkingManager.application(
        UIApplication.shared, continue: activity, restorationHandler: { _ in })
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      _ = RCTLinkingManager.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = RCTLinkingManager.application(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

const WINDOW_BLOCK =
  /#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\(\n\s*withModuleName: "main",\n\s*in: window,\n\s*launchOptions: launchOptions\)\n#endif\n/;
const FACTORY_PROPERTY = /(\n(\s*)var reactNativeFactory: RCTReactNativeFactory\?\n)/;

function transformAppDelegate(src) {
  if (src.includes('self.launchOptions = launchOptions')) return src;   // already applied
  if (!WINDOW_BLOCK.test(src) || !FACTORY_PROPERTY.test(src)) {
    throw new Error(
      'withSceneLifecycle: AppDelegate.swift no longer matches the Expo SDK 57 template. ' +
      'Update the anchors in plugins/withSceneLifecycle.js — without this edit the app ' +
      'crashes at launch on iOS 27.');
  }
  return src
    .replace(FACTORY_PROPERTY, '$1$2var launchOptions: [UIApplication.LaunchOptionsKey: Any]?\n')
    .replace(WINDOW_BLOCK,
      '    // The window belongs to the scene (UIScene life cycle, required on iOS 27):\n' +
      '    // SceneDelegate creates it and starts React Native when the scene connects.\n' +
      '    self.launchOptions = launchOptions\n');
}

module.exports = function withSceneLifecycle(config) {
  config = withInfoPlist(config, cfg => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [{
          UISceneConfigurationName: 'Default Configuration',
          UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
        }],
      },
    };
    return cfg;
  });

  config = withAppDelegate(config, cfg => {
    if (cfg.modResults.language !== 'swift') {
      throw new Error('withSceneLifecycle expects a Swift AppDelegate');
    }
    cfg.modResults.contents = transformAppDelegate(cfg.modResults.contents);
    return cfg;
  });

  config = withDangerousMod(config, ['ios', async cfg => {
    const name = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    fs.writeFileSync(path.join(cfg.modRequest.platformProjectRoot, name, 'SceneDelegate.swift'), SCENE_DELEGATE);
    return cfg;
  }]);

  return withXcodeProject(config, cfg => {
    const name = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = path.join(name, 'SceneDelegate.swift');
    if (!cfg.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: name, project: cfg.modResults });
    }
    return cfg;
  });
};

module.exports.transformAppDelegate = transformAppDelegate;
